-- Los campos se dejan inicialmente nullable para permitir migrar filas existentes.
-- Tras completar los datos, aplicar NOT NULL con la comprobacion al final del archivo.
CREATE UNIQUE INDEX IF NOT EXISTS uq_esart_usuario_nombre_ci
 ON esart_ref.usuarios (lower(usuario)) WHERE usuario IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_esart_usuario_documento
 ON esart_ref.usuarios (documento_identidad) WHERE documento_identidad IS NOT NULL;
ALTER TABLE esart_ref.usuarios
 ADD CONSTRAINT ck_esart_usuario_hash_no_vacio CHECK (contrasena_hash IS NULL OR length(trim(contrasena_hash)) > 0);

CREATE TABLE IF NOT EXISTS esart.roles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(30) NOT NULL UNIQUE,
 nombre varchar(100) NOT NULL,
 descripcion text,
 activo boolean NOT NULL DEFAULT true,
 creado_en timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT ck_esart_roles_codigo CHECK (codigo IN ('ADMINISTRADOR','USUARIO'))
);
CREATE TABLE IF NOT EXISTS esart.usuario_roles (
 usuario_id bigint NOT NULL REFERENCES esart_ref.usuarios(id) ON DELETE CASCADE,
 rol_id bigint NOT NULL REFERENCES esart.roles(id) ON DELETE RESTRICT,
 asignado_en timestamptz NOT NULL DEFAULT now(),
 asignado_por_id bigint REFERENCES esart_ref.usuarios(id) ON DELETE SET NULL,
 PRIMARY KEY (usuario_id, rol_id)
);
CREATE INDEX IF NOT EXISTS ix_esart_usuario_roles_rol ON esart.usuario_roles(rol_id);

CREATE TABLE IF NOT EXISTS esart.componentes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(100) NOT NULL UNIQUE,
 nombre varchar(150) NOT NULL,
 ruta_angular varchar(250),
 descripcion text,
 componente_padre_id bigint REFERENCES esart.componentes(id) ON DELETE RESTRICT,
 orden int NOT NULL DEFAULT 0,
 activo boolean NOT NULL DEFAULT true,
 creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_esart_componentes_padre ON esart.componentes(componente_padre_id);

-- Malla de permisos por rol: acceso a la pantalla + permisos CRUD.
CREATE TABLE IF NOT EXISTS esart.rol_permisos (
 rol_id bigint NOT NULL REFERENCES esart.roles(id) ON DELETE CASCADE,
 componente_id bigint NOT NULL REFERENCES esart.componentes(id) ON DELETE CASCADE,
 puede_acceder boolean NOT NULL DEFAULT false,
 puede_crear boolean NOT NULL DEFAULT false,
 puede_leer boolean NOT NULL DEFAULT false,
 puede_actualizar boolean NOT NULL DEFAULT false,
 puede_eliminar boolean NOT NULL DEFAULT false,
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (rol_id, componente_id),
 CONSTRAINT ck_esart_rol_crud_acceso CHECK (
   puede_acceder OR NOT (puede_crear OR puede_leer OR puede_actualizar OR puede_eliminar)
 )
);
CREATE INDEX IF NOT EXISTS ix_esart_rol_permisos_componente ON esart.rol_permisos(componente_id);

-- Excepciones por usuario: si existe una fila, sustituye los permisos del rol
-- para ese componente. Permite conceder o denegar accesos individuales.
CREATE TABLE IF NOT EXISTS esart.usuario_permisos (
 usuario_id bigint NOT NULL REFERENCES esart_ref.usuarios(id) ON DELETE CASCADE,
 componente_id bigint NOT NULL REFERENCES esart.componentes(id) ON DELETE CASCADE,
 puede_acceder boolean NOT NULL DEFAULT false,
 puede_crear boolean NOT NULL DEFAULT false,
 puede_leer boolean NOT NULL DEFAULT false,
 puede_actualizar boolean NOT NULL DEFAULT false,
 puede_eliminar boolean NOT NULL DEFAULT false,
 actualizado_en timestamptz NOT NULL DEFAULT now(),
 actualizado_por_id bigint REFERENCES esart_ref.usuarios(id) ON DELETE SET NULL,
 PRIMARY KEY (usuario_id, componente_id),
 CONSTRAINT ck_esart_usuario_crud_acceso CHECK (
   puede_acceder OR NOT (puede_crear OR puede_leer OR puede_actualizar OR puede_eliminar)
 )
);
CREATE INDEX IF NOT EXISTS ix_esart_usuario_permisos_componente ON esart.usuario_permisos(componente_id);

