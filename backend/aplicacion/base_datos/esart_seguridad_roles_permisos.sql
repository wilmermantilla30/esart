-- Permisos efectivos: union de permisos de roles; las excepciones individuales
-- prevalecen sobre el resultado. Usuarios inactivos no reciben permisos.
CREATE OR REPLACE VIEW esart.v_permisos_efectivos AS
WITH por_rol AS (
 SELECT ur.usuario_id,rp.componente_id,
  bool_or(rp.puede_acceder) AS puede_acceder,
  bool_or(rp.puede_crear) AS puede_crear,
  bool_or(rp.puede_leer) AS puede_leer,
  bool_or(rp.puede_actualizar) AS puede_actualizar,
  bool_or(rp.puede_eliminar) AS puede_eliminar
 FROM esart.usuario_roles ur
 JOIN esart.roles r ON r.id=ur.rol_id AND r.activo
 JOIN esart.rol_permisos rp ON rp.rol_id=r.id
 GROUP BY ur.usuario_id,rp.componente_id
)
SELECT u.id AS usuario_id,c.id AS componente_id,c.codigo AS componente,
 COALESCE(up.puede_acceder,pr.puede_acceder,false) AS puede_acceder,
 COALESCE(up.puede_crear,pr.puede_crear,false) AS puede_crear,
 COALESCE(up.puede_leer,pr.puede_leer,false) AS puede_leer,
 COALESCE(up.puede_actualizar,pr.puede_actualizar,false) AS puede_actualizar,
 COALESCE(up.puede_eliminar,pr.puede_eliminar,false) AS puede_eliminar
FROM esart_ref.usuarios u
CROSS JOIN esart.componentes c
LEFT JOIN por_rol pr ON pr.usuario_id=u.id AND pr.componente_id=c.id
LEFT JOIN esart.usuario_permisos up ON up.usuario_id=u.id AND up.componente_id=c.id
WHERE u.activo AND c.activo;

COMMIT;

