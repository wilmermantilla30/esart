-- No crea usuarios ni contrasenas predeterminadas.
BEGIN;
CREATE SCHEMA IF NOT EXISTS esart;
CREATE SCHEMA IF NOT EXISTS esart_ref;

-- Verificar que exista la tabla original; evita crear una tabla paralela.
DO $$ BEGIN
 IF to_regclass('esart_ref.usuarios') IS NULL THEN
   RAISE EXCEPTION 'Falta esart_ref.usuarios. Ejecute primero el esquema base ESART.';
 END IF;
END $$;

ALTER TABLE esart_ref.usuarios
 ADD COLUMN IF NOT EXISTS usuario varchar(80),
 ADD COLUMN IF NOT EXISTS contrasena_hash text,
