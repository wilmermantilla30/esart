-- ESART / PostgreSQL: carga real de catalogos y unidades en esart_db.
-- Ejecutar en DBCode con conexion administrativa a esart_db, tras respaldo verificado.
-- Una sola transaccion. No altera alembic_version ni crea otra base de datos.
BEGIN;
DO $$ BEGIN
  IF current_database() <> 'esart_db' THEN
    RAISE EXCEPTION 'Conexion incorrecta: se requiere esart_db, actual %', current_database();
  END IF;
  IF to_regclass('esart_ref.unidades_militares') IS NULL THEN
    RAISE EXCEPTION 'Falta la tabla esart_ref.unidades_militares';
  END IF;
  IF to_regclass('esart.tipos_cargo') IS NULL OR to_regclass('esart.tipos_curso') IS NULL THEN
    RAISE EXCEPTION 'Faltan tablas academicas esart.tipos_cargo o esart.tipos_curso';
  END IF;
END $$;

-- Extender tabla existente, conservando su PK BIGINT y sus FK entrantes.
CREATE TABLE IF NOT EXISTS esart.tipos_unidad (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE esart_ref.unidades_militares
  ADD COLUMN IF NOT EXISTS codigo VARCHAR(30),
  ADD COLUMN IF NOT EXISTS nombre VARCHAR(200),
  ADD COLUMN IF NOT EXISTS tipo_unidad_id BIGINT,
  ADD COLUMN IF NOT EXISTS unidad_padre_id BIGINT,
  ADD COLUMN IF NOT EXISTS latitud DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS longitud DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE,
  ADD COLUMN IF NOT EXISTS fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now();

-- No pisar datos previos ni imponer indices incompatibles sobre datos existentes.
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM esart_ref.unidades_militares WHERE codigo IS NOT NULL GROUP BY codigo HAVING count(*) > 1) THEN
  RAISE EXCEPTION 'Hay codigos de unidad duplicados; no se puede crear indice unico';
 END IF;
 IF EXISTS (SELECT 1 FROM esart_ref.unidades_militares WHERE tipo_unidad_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM esart.tipos_unidad t WHERE t.id = tipo_unidad_id)) THEN
  RAISE EXCEPTION 'Existen referencias de tipos de unidad sin destino';
 END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS uq_esart_ref_unidades_codigo ON esart_ref.unidades_militares(codigo);
CREATE INDEX IF NOT EXISTS ix_esart_ref_unidades_padre ON esart_ref.unidades_militares(unidad_padre_id);
CREATE INDEX IF NOT EXISTS ix_esart_ref_unidades_tipo ON esart_ref.unidades_militares(tipo_unidad_id);
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_esart_unidades_tipo' AND conrelid='esart_ref.unidades_militares'::regclass) THEN
  ALTER TABLE esart_ref.unidades_militares ADD CONSTRAINT fk_esart_unidades_tipo FOREIGN KEY(tipo_unidad_id) REFERENCES esart.tipos_unidad(id);
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_esart_unidades_padre' AND conrelid='esart_ref.unidades_militares'::regclass) THEN
  ALTER TABLE esart_ref.unidades_militares ADD CONSTRAINT fk_esart_unidades_padre FOREIGN KEY(unidad_padre_id) REFERENCES esart_ref.unidades_militares(id);
 END IF;
END $$;

