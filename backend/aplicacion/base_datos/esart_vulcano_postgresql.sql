    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_curso_id bigint NOT NULL,
    semestre_id bigint NOT NULL,
    comandante_id bigint NOT NULL,
    codigo varchar(30) NOT NULL UNIQUE,
    nombre varchar(200) NOT NULL,
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    CONSTRAINT ck_cursos_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    estado varchar(20) NOT NULL DEFAULT 'PLANEADO',
    CONSTRAINT ck_cursos_estado CHECK (estado IN ('PLANEADO','EN_EJECUCION','FINALIZADO','CANCELADO')),
    observaciones text,
    creado_por_id bigint NOT NULL,
    creado_en timestamptz NOT NULL DEFAULT now()
