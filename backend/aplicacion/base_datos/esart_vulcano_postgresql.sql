    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(200) NOT NULL,
    tipo varchar(50),
    modalidad varchar(30) NOT NULL,
