CREATE TABLE IF NOT EXISTS esart.materias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(200) NOT NULL,
