CREATE TABLE IF NOT EXISTS esart.habilitaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_activo_id bigint NOT NULL,
    nota_materia_id bigint NOT NULL,
    numero_habilitacion integer NOT NULL CHECK (numero_habilitacion BETWEEN 1 AND 2),
    fecha_habilitacion date NOT NULL,
    nota_obtenida numeric(5,2) CHECK (nota_obtenida >= 0 AND nota_obtenida <= 100),
    resultado varchar(20) NOT NULL,
    CONSTRAINT ck_habilitaciones_resultado CHECK (resultado IN ('APROBADA','REPROBADA')),
    registrado_por_id bigint NOT NULL,
    creado_en timestamptz NOT NULL DEFAULT now()
