CREATE TABLE IF NOT EXISTS esart.notas_materia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_activo_id bigint NOT NULL,
    malla_id bigint NOT NULL,
    nota numeric(5,2) CHECK (nota >= 0 AND nota <= 100),
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE',
    nota_habilitacion numeric(5,2) CHECK (nota_habilitacion >= 0 AND nota_habilitacion <= 100),
    fecha_evaluacion date,
    fecha_habilitacion date
