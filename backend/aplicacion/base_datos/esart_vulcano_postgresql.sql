CREATE TABLE IF NOT EXISTS esart.inscripciones_curso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id bigint NOT NULL,
    personal_id bigint NOT NULL,
    fecha_inscripcion date NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'INSCRITO',
    CONSTRAINT ck_inscripciones_estado CHECK (estado IN ('INSCRITO','SELECCIONADO','RETIRADO','GRADUADO','REPROBADO')),
    nota_final numeric(5,2) CHECK (nota_final >= 0 AND nota_final <= 100),
    fecha_resultado date,
    observaciones text
);

CREATE TABLE IF NOT EXISTS esart.alumnos_activos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personal_id bigint NOT NULL,
    curso_id bigint NOT NULL,
    inscripcion_id bigint NOT NULL,
    fecha_ingreso_escuela date NOT NULL,
    fecha_fin_prevista date NOT NULL,
    estado_alumno varchar(20) NOT NULL DEFAULT 'EN_CURSO',
    CONSTRAINT ck_alumnos_estado CHECK (estado_alumno IN ('EN_CURSO','SUSPENDIDO','EN_HABILITACION')),
