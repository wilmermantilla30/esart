CREATE TABLE IF NOT EXISTS esart.artillero_cargos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hoja_vida_id bigint NOT NULL,
    tipo_cargo_id bigint NOT NULL,
