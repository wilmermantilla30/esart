def _restriccion_acciones(acciones: tuple[str, ...]) -> None:
    lista = ", ".join(f"'{accion}'" for accion in acciones)
    op.execute(f"ALTER TABLE esart.auditoria_eventos DROP CONSTRAINT {NOMBRE_RESTRICCION}")
    op.execute(
        f"ALTER TABLE esart.auditoria_eventos ADD CONSTRAINT {NOMBRE_RESTRICCION} CHECK (accion IN ({lista}))"  # noqa: S608
    )


def upgrade():
    # Una entrega por curso y materia; volver a subir reemplaza sus notas (el historial queda
    # en la auditoría). Los campos de revisión los usará el Inspector (S2-13).
    op.execute("""
        CREATE TABLE esart.entregas_notas (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY,
            curso_id BIGINT NOT NULL,
            malla_id BIGINT NOT NULL,
            instructor_id BIGINT NOT NULL,
            estado VARCHAR(20) NOT NULL DEFAULT 'EN_REVISION',
            nombre_archivo VARCHAR(200) NOT NULL,
            sha256 CHAR(64) NOT NULL,
            subido_por_id BIGINT,
            subido_en TIMESTAMPTZ NOT NULL DEFAULT now(),
            revisado_por_id BIGINT,
            revisado_en TIMESTAMPTZ,
            observacion_revision TEXT,
            CONSTRAINT entregas_notas_pkey PRIMARY KEY (id),
            CONSTRAINT fk_entregas_notas_curso_id FOREIGN KEY (curso_id) REFERENCES esart.cursos (id),
            CONSTRAINT fk_entregas_notas_malla_id FOREIGN KEY (malla_id)
              REFERENCES esart.malla_curricular (id),
            CONSTRAINT fk_entregas_notas_instructor_id FOREIGN KEY (instructor_id)
              REFERENCES esart.instructores (id),
            CONSTRAINT fk_entregas_notas_subido_por_id FOREIGN KEY (subido_por_id)
              REFERENCES esart_ref.usuarios (id) ON DELETE SET NULL,
            CONSTRAINT fk_entregas_notas_revisado_por_id FOREIGN KEY (revisado_por_id)
              REFERENCES esart_ref.usuarios (id) ON DELETE SET NULL,
            CONSTRAINT ck_entregas_notas_estado CHECK (estado IN ('EN_REVISION', 'APROBADA', 'DEVUELTA')),
            CONSTRAINT uq_entregas_notas_curso_malla UNIQUE (curso_id, malla_id)
        )
    """)
    op.execute("CREATE INDEX ix_entregas_notas_estado ON esart.entregas_notas (estado)")
    op.execute("CREATE INDEX ix_entregas_notas_instructor_id ON esart.entregas_notas (instructor_id)")
    op.execute("""
        CREATE TABLE esart.notas_entrega (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY,
            entrega_id BIGINT NOT NULL,
            personal_id BIGINT NOT NULL,
            nota NUMERIC(3, 2) NOT NULL,
            CONSTRAINT notas_entrega_pkey PRIMARY KEY (id),
            CONSTRAINT fk_notas_entrega_entrega_id FOREIGN KEY (entrega_id)
              REFERENCES esart.entregas_notas (id) ON DELETE CASCADE,
            CONSTRAINT fk_notas_entrega_personal_id FOREIGN KEY (personal_id)
              REFERENCES esart.personal_militar (id),
            CONSTRAINT ck_notas_entrega_nota CHECK (nota >= 0 AND nota <= 5),
            CONSTRAINT uq_notas_entrega_alumno UNIQUE (entrega_id, personal_id)
        )
    """)
    op.execute("CREATE INDEX ix_notas_entrega_personal_id ON esart.notas_entrega (personal_id)")

    op.execute(f"UPDATE esart.componentes SET ruta_angular = '{RUTA_CARGA}' WHERE codigo = 'NOTAS_CARGA'")  # noqa: S608
