def _restriccion_acciones(acciones: tuple[str, ...]) -> None:
    lista = ", ".join(f"'{accion}'" for accion in acciones)
    op.execute(f"ALTER TABLE esart.auditoria_eventos DROP CONSTRAINT {NOMBRE_RESTRICCION}")
    op.execute(
        f"ALTER TABLE esart.auditoria_eventos ADD CONSTRAINT {NOMBRE_RESTRICCION} CHECK (accion IN ({lista}))"  # noqa: S608
    )


def upgrade():
    # Notas que cuentan: se reemplazan completas (por curso y materia) en cada aprobación.
    op.execute("""
        CREATE TABLE esart.notas_oficiales (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY,
            curso_id BIGINT NOT NULL,
            malla_id BIGINT NOT NULL,
            personal_id BIGINT NOT NULL,
            nota NUMERIC(3, 2) NOT NULL,
            entrega_id BIGINT NOT NULL,
            aprobado_por_id BIGINT,
            aprobado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
            CONSTRAINT notas_oficiales_pkey PRIMARY KEY (id),
            CONSTRAINT fk_notas_oficiales_curso_id FOREIGN KEY (curso_id) REFERENCES esart.cursos (id),
            CONSTRAINT fk_notas_oficiales_malla_id FOREIGN KEY (malla_id)
              REFERENCES esart.malla_curricular (id),
            CONSTRAINT fk_notas_oficiales_personal_id FOREIGN KEY (personal_id)
              REFERENCES esart.personal_militar (id),
            CONSTRAINT fk_notas_oficiales_entrega_id FOREIGN KEY (entrega_id)
              REFERENCES esart.entregas_notas (id),
            CONSTRAINT fk_notas_oficiales_aprobado_por_id FOREIGN KEY (aprobado_por_id)
              REFERENCES esart_ref.usuarios (id) ON DELETE SET NULL,
            CONSTRAINT ck_notas_oficiales_nota CHECK (nota >= 0 AND nota <= 5),
            CONSTRAINT uq_notas_oficiales_alumno UNIQUE (curso_id, malla_id, personal_id)
        )
    """)
    op.execute("CREATE INDEX ix_notas_oficiales_personal_id ON esart.notas_oficiales (personal_id)")

    op.execute(
        f"UPDATE esart.componentes SET ruta_angular = '{RUTA_REVISION}' WHERE codigo = 'NOTAS_REVISION'"  # noqa: S608
    )
    op.execute(f"""
        DO $$
        BEGIN
          IF to_regclass('seguridad.politicas_accion') IS NOT NULL THEN
            INSERT INTO seguridad.politicas_accion (codigo, nombre, modulo, requiere_totp)
            VALUES ('{POLITICA_TOTP}', 'Aprobar y reabrir entregas de notas', 'NOTAS', true)
            ON CONFLICT (codigo) DO NOTHING;
          END IF;
        END $$;
    """)  # noqa: S608
    _restriccion_acciones(ACCIONES_ANTERIORES + ACCIONES_NUEVAS)
    op.execute(f"""
        DO $$
        BEGIN
          IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{CUENTA_APLICACION}') THEN
            GRANT SELECT, INSERT, DELETE ON esart.notas_oficiales TO {CUENTA_APLICACION};
            EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO {CUENTA_APLICACION}',
                           pg_get_serial_sequence('esart.notas_oficiales', 'id'));
          END IF;
        END $$;
    """)  # noqa: S608


def downgrade():
    # Solo funciona si no hay eventos con las acciones nuevas (la auditoría es inmutable).
    _restriccion_acciones(ACCIONES_ANTERIORES)
    op.execute(f"""
        DO $$
        BEGIN
          IF to_regclass('seguridad.politicas_accion') IS NOT NULL THEN
            DELETE FROM seguridad.politicas_accion WHERE codigo = '{POLITICA_TOTP}';
          END IF;
        END $$;
    """)  # noqa: S608
    op.execute("UPDATE esart.componentes SET ruta_angular = NULL WHERE codigo = 'NOTAS_REVISION'")
    op.execute("DROP TABLE esart.notas_oficiales")
