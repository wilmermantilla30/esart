"""S2-13: el Inspector de Estudios revisa las entregas de notas.

Decisiones (SS.Mantilla, 2026-11-26):
- El Inspector aprueba (con TOTP) o devuelve (con observación) cada entrega EN_REVISION.
- Al aprobar, las notas pasan a esart.notas_oficiales: son las que cuentan para la habilitación
  (S2-14) y la nota final (S2-15).
- Para corregir una nota oficial, el Inspector REABRE la entrega aprobada (TOTP y observación):
  queda DEVUELTA y el instructor sube la corrección. Las notas oficiales anteriores siguen
  vigentes hasta la nueva aprobación, y esa aprobación audita el antes y el después.
- Permiso NOTAS_REVISION: leer para la bandeja, actualizar para aprobar, devolver o reabrir.

Cambios:
- esart.notas_oficiales (una nota por curso, materia y alumno).
- NOTAS_REVISION tiene ruta (/notas/revision): aparece en el menú de quien lo tenga.
- Política TOTP NOTAS_APROBAR; acciones de auditoría NOTAS_APROBADAS, NOTAS_DEVUELTAS y
  NOTAS_REABIERTAS.
"""

