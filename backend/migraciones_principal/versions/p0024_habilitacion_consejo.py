"""S2-14: habilitación de materias perdidas y decisiones del Consejo Académico.

Decisiones (SS.Mantilla, 2026-11-26):
- Pendiente de habilitación: alumno cuya nota oficial ORDINARIA de una materia quedó por debajo
  de la nota mínima del curso. Una sola habilitación por materia.
- El instructor registra la nota de habilitación en un formulario en pantalla (sin Excel). Esa
  "entrega de habilitación" pasa por la misma revisión del Inspector (S2-13) con TOTP.
- Al aprobarse: si la nota de habilitación alcanza la mínima, es la que cuenta (materia
  "Habilitada"); si no, el alumno queda "En Consejo Académico".
- El Consejo registra su decisión (lista fija, número y fecha de acta, observación) con TOTP y
  permiso CONSEJO_ACADEMICO. "Aprueba la materia" la deja con la nota mínima del curso.
- No se reabren notas ordinarias de una materia que ya tiene habilitación (ni la habilitación de
  un alumno con decisión del Consejo).

Cambios:
- entregas_notas.tipo (ORDINARIA | HABILITACION): una entrega de cada tipo por curso y materia.
- notas_oficiales.nota_ordinaria (la nota con que perdió o ganó la materia) y .origen
  (ORDINARIA | HABILITACION | CONSEJO): nota es la que cuenta para el promedio.
- esart.habilitaciones_materia (resultado de cada habilitación aprobada) y
  esart.decisiones_consejo (una por habilitación perdida). La tabla esart.habilitaciones de la
  fase 1 (ligada a alumnos_activos / notas_materia, vacías) no se usa.
- CONSEJO_ACADEMICO tiene ruta (/notas/consejo); política TOTP CONSEJO_REGISTRAR; acción de
  auditoría CONSEJO_DECISION_REGISTRADA.
"""

