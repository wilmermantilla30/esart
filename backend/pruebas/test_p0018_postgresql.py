@pytest.mark.parametrize(
    ("definicion", "compatible"),
    [
        ("CHECK (((proposito) = ('FIRMAR')))", True),
        ("CHECK (proposito IN ('FIRMAR', 'LOGIN'))", False),
        ("CHECK (proposito = 'FIRMAR') NOT VALID", False),
    ],
)
def test_check_solo_firma_preexistente(laboratorio, definicion, compatible, capsys):
    lab = laboratorio

    async def ejecutar_caso():
        documentos = migracion.TABLAS_DOCUMENTALES
        tablas = (*documentos, "auditoria_eventos")
        await preparar(lab, heredado=True, documentos=documentos)
        consulta_check = """
            SELECT oid, pg_get_constraintdef(oid, true), convalidated
            FROM pg_constraint WHERE conname = 'ck_desafios_solo_firma'
        """
        async with conectar(lab) as con:
            await con.execute(
                "ALTER TABLE esart_firma.desafios_autenticacion "
                f"ADD CONSTRAINT ck_desafios_solo_firma {definicion}"  # noqa: S608
            )
            check_antes = await con.fetchrow(consulta_check)
            antes = await huellas(con, tablas)

        motor = create_async_engine(lab.url("esart_migrador", BASE), connect_args={"ssl": False})
        try:
            async with motor.begin() as con:
                if compatible:
                    await con.run_sync(auditar_heredado)
                    auditoria = capsys.readouterr().out
                    assert sum(linea.endswith(": compatible") for linea in auditoria.splitlines()) == 23
                    assert "ck_desafios_solo_firma" in auditoria
                else:
                    with pytest.raises(RuntimeError, match="ck_desafios_solo_firma"):
                        await con.run_sync(auditar_heredado)
        finally:
            await motor.dispose()

        codigo, salida = alembic(lab, "upgrade", OBJETIVO)
        if compatible:
            assert codigo == 0, salida
        else:
            assert codigo != 0 and "ck_desafios_solo_firma" in salida, salida
        async with conectar(lab) as con:
            assert await estado(con) == (OBJETIVO if compatible else ANTERIOR)
            assert await con.fetchrow(consulta_check) == check_antes
            assert await huellas(con, tablas) == antes

    asyncio.run(ejecutar_caso())


