async def huellas(con, tablas):
    resultado = {}
    for tabla in tablas:
        oid = await con.fetchval("SELECT to_regclass($1)::oid", f"esart_firma.{tabla}")
        # La evidencia del laboratorio es independiente de la comprobación interna.
        filas = await con.fetch(
            f"SELECT to_jsonb(t)::text AS fila FROM esart_firma.{tabla} t ORDER BY id"  # noqa: S608
        )
        digest = hashlib.sha256("\n".join(f["fila"] for f in filas).encode()).hexdigest()
        resultado[tabla] = (oid, len(filas), digest)
    return resultado


async def estado(con):
    return await con.fetchval("SELECT version_num FROM esart.alembic_version")


@pytest.mark.parametrize(
    "modo", ["compatible", "check-distinto", "funcion-condicional", "security-definer", "search-path"]
)
def test_conciliacion_checks_y_funcion(laboratorio, modo):
    lab = laboratorio

    def ddl_documentos(esquema, tabla):
        for sentencia in migracion._ddl_documental(esquema, tabla):
            sentencia = sentencia.replace(
                "tipo IN ('CERTIFICACION', 'OFICIO_REMISORIO')",
                ("tipo::text = ANY (ARRAY['CERTIFICACION'::text, 'OFICIO_REMISORIO'::text])"),
            )
            valores_estado = (
                "'BORRADOR'::text, 'PENDIENTE_FIRMA'::text, 'FIRMADO'::text, 'EMITIDO'::text, 'ANULADO'::text"
            )
            if modo == "check-distinto":
                valores_estado += ", 'EXTRA'::text"
            yield sentencia.replace(
                "estado IN ('BORRADOR','PENDIENTE_FIRMA','FIRMADO','EMITIDO','ANULADO')",
                f"estado::text = ANY (ARRAY[{valores_estado}])",
            )

    async def ejecutar_caso():
        documentos = migracion.TABLAS_DOCUMENTALES
        await preparar(lab, heredado=True, documentos=documentos, ddl_documentos=ddl_documentos)
        tablas = (*documentos, "auditoria_eventos")
        async with conectar(lab) as con:
            assert await con.fetchval("""
                WITH arrays(a, b) AS (VALUES
                    (ARRAY['CERTIFICACION'::varchar, 'OFICIO_REMISORIO'::varchar]::text[],
                     ARRAY['CERTIFICACION'::text, 'OFICIO_REMISORIO'::text]),
                    (ARRAY['BORRADOR'::varchar, 'PENDIENTE_FIRMA'::varchar, 'FIRMADO'::varchar,
                           'EMITIDO'::varchar, 'ANULADO'::varchar]::text[],
                     ARRAY['BORRADOR'::text, 'PENDIENTE_FIRMA'::text, 'FIRMADO'::text,
                           'EMITIDO'::text, 'ANULADO'::text])
                )
                SELECT bool_and(a IS NOT DISTINCT FROM b
                            AND (v = ANY(a)) IS NOT DISTINCT FROM (v = ANY(b)))
                FROM arrays CROSS JOIN LATERAL unnest(a || ARRAY[NULL, '', 'OTRO']::text[]) AS valores(v)
            """)
            cuerpo = "begin raise exception 'Autenticación heredada deshabilitada'; end;"
            if modo == "funcion-condicional":
                cuerpo = "BEGIN IF TG_OP = 'INSERT' THEN RAISE EXCEPTION 'Bloqueado'; END IF; RETURN NEW; END"
            atributos = {"security-definer": "SECURITY DEFINER", "search-path": "SET search_path = public"}
            await con.execute(f"""
                CREATE FUNCTION esart_firma.rechazar_autenticacion_heredada()
                RETURNS trigger LANGUAGE plpgsql {atributos.get(modo, "")} AS $fn${cuerpo}$fn$;
            """)
            for tabla in migracion.TABLAS_AUTENTICACION_HEREDADA:
                await con.execute(migracion._ddl_trigger(tabla))
            antes = await huellas(con, tablas)
            consulta_oids = """
                SELECT c.relname, c.oid FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'esart_firma' AND c.relkind = 'r' ORDER BY c.relname
            """
            oids_antes = await con.fetch(consulta_oids)
            assert len(oids_antes) == 23
            objetos = await objetos_adoptados(con)
            checks = """
                SELECT oid, pg_get_constraintdef(oid, true) FROM pg_constraint
                WHERE conrelid = 'esart_firma.documentos'::regclass
                  AND conname IN ('ck_documentos_tipo', 'ck_documentos_estado') ORDER BY conname
            """
            checks_antes = await con.fetch(checks)

        codigo, salida = alembic(lab, "upgrade", OBJETIVO)
        assert (codigo == 0) == (modo == "compatible"), salida
        if modo == "check-distinto":
            assert "restricciones incompatibles" in salida and "ck_documentos_estado" in salida
        elif modo != "compatible":
            assert "cuerpo o atributos incompatibles" in salida
        async with conectar(lab) as con:
            assert await estado(con) == (OBJETIVO if modo == "compatible" else ANTERIOR)
            assert await huellas(con, tablas) == antes
            assert await con.fetch(consulta_oids) == oids_antes
            objetos_despues = await objetos_adoptados(con)
            assert all(objeto in objetos_despues for objeto in objetos)
            if modo != "compatible":
                assert objetos_despues == objetos
            assert await con.fetch(checks) == checks_antes
            if modo == "compatible":
                await con.execute("""
                    CREATE TEMP TABLE probar_rechazo (id integer);
                    INSERT INTO probar_rechazo VALUES (1);
                    CREATE TRIGGER proteger BEFORE INSERT OR UPDATE ON probar_rechazo
                    FOR EACH ROW EXECUTE FUNCTION esart_firma.rechazar_autenticacion_heredada();
                """)
                for sql in ("INSERT INTO probar_rechazo VALUES (2)", "UPDATE probar_rechazo SET id = 3"):
                    with pytest.raises(asyncpg.RaiseError, match="Autenticación heredada deshabilitada"):
                        await con.execute(sql)

    asyncio.run(ejecutar_caso())


async def objetos_adoptados(con):
    return await con.fetch("""
        SELECT 'trigger' AS clase, tgname || ':' || tgrelid::text AS nombre, oid
        FROM pg_trigger WHERE tgname = 'trg_autenticacion_heredada'
        UNION ALL
        SELECT 'funcion', proname, oid FROM pg_proc WHERE proname = 'rechazar_autenticacion_heredada'
        UNION ALL
        SELECT 'restriccion', conname, oid FROM pg_constraint
        WHERE conname IN ('fk_identidades_usuario', 'fk_evidencias_documento',
                          'fk_solicitudes_version_documento', 'ck_solicitudes_objeto_unico')
        UNION ALL
        SELECT 'indice', relname, oid FROM pg_class
        WHERE relname IN ('uq_identidades_usuario', 'ix_evidencias_documento',
                          'uq_solicitudes_documento_firmante')
        ORDER BY clase, nombre
    """)


@pytest.mark.parametrize("modo", ["completo", "incompatible", "parcial"])
def test_adopcion_seis_diferencias(laboratorio, modo, capsys):
    lab = laboratorio
    compatible = modo != "incompatible"

    async def ejecutar_caso():
        documentos = migracion.TABLAS_DOCUMENTALES
        await preparar(lab, heredado=True, documentos=documentos)
        async with conectar(lab) as con:
            await con.execute(f"""
                CREATE FUNCTION esart_firma.rechazar_autenticacion_heredada()
                RETURNS trigger LANGUAGE plpgsql AS $fn${migracion.CUERPO_FUNCION}$fn$;
            """)
            triggers = migracion.TABLAS_AUTENTICACION_HEREDADA
            if modo == "parcial":
                triggers = triggers[:2]
            for tabla in triggers:
                ddl = migracion._ddl_trigger(tabla)
                if not compatible:
                    ddl = ddl.replace("BEFORE INSERT OR UPDATE", "BEFORE INSERT")
                await con.execute(ddl)
            for tabla, columnas in migracion.COLUMNAS_NUEVAS.items():
                for campo, tipo in columnas.items():
                    if not compatible:
                        tipo += {
                            "identidades": " DEFAULT 3",
                            "evidencias": " NOT NULL",
                            "solicitudes_firma": "",
                        }[tabla]
                        if tabla == "solicitudes_firma" and campo == "documento_version_id":
                            tipo = "text"
                    await con.execute(f"ALTER TABLE esart_firma.{tabla} ADD COLUMN {campo} {tipo}")  # noqa: S608
            if compatible:
                await con.execute("""
                    ALTER TABLE esart_firma.solicitudes_firma
                    ALTER COLUMN certificado_id DROP NOT NULL, ALTER COLUMN version_id DROP NOT NULL;
                    INSERT INTO esart_firma.identidades (usuario_externo_id, nombre_mostrado, usuario_id)
                    VALUES ('previo', 'Identidad previa', 3);
                """)
                for tabla in migracion.COLUMNAS_NUEVAS:
                    if modo == "parcial" and tabla == "evidencias":
                        continue
                    for _, nombre, definicion in migracion.RESTRICCIONES_NUEVAS[tabla]:
                        await con.execute(
                            f"ALTER TABLE esart_firma.{tabla} ADD CONSTRAINT {nombre} {definicion}"  # noqa: S608
                        )
                    await con.execute(migracion.INDICES_NUEVOS[tabla][1])
            tablas = (*documentos, "auditoria_eventos", "identidades", "evidencias", "solicitudes_firma")
            antes = await huellas(con, tablas)
            objetos_antes = await objetos_adoptados(con)

        motor = create_async_engine(lab.url("esart_migrador", BASE), connect_args={"ssl": False})
        try:
            async with motor.begin() as con:
                if compatible:
                    await con.run_sync(auditar_heredado)
                    informe = capsys.readouterr().out
                    assert "columna de p0018 usuario_id: tipo=bigint, NOT NULL=False, default=None" in informe
                    assert informe.count("disparadores adoptables:") == len(triggers)
                else:
                    with pytest.raises(RuntimeError) as error:
                        await con.run_sync(auditar_heredado)
                    for tabla in (*migracion.COLUMNAS_NUEVAS, *migracion.TABLAS_AUTENTICACION_HEREDADA):
                        assert f"esart_firma.{tabla} " in str(error.value)
                    for detalle in (
                        "usuario_id.default",
                        "documento_id.NOT NULL",
                        "documento_version_id.tipo",
                    ):
                        assert detalle in str(error.value)
        finally:
            await motor.dispose()
        codigo, salida = alembic(lab, "upgrade", OBJETIVO)
        assert (codigo == 0) == compatible, salida
        async with conectar(lab) as con:
            assert await estado(con) == (OBJETIVO if compatible else ANTERIOR)
            assert await huellas(con, tablas) == antes
            objetos_despues = await objetos_adoptados(con)
            if modo == "parcial":
                assert len(objetos_despues) == len(objetos_antes) + 3
                assert all(objeto in objetos_despues for objeto in objetos_antes)
            else:
                assert objetos_despues == objetos_antes

    asyncio.run(ejecutar_caso())


