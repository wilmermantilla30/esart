@asynccontextmanager
async def conectar(lab, rol="esart_migrador", base=BASE):
    con = await lab.conectar(rol, base)
    try:
        yield con
    finally:
        await con.close()


def alembic(lab, accion, revision, *, bandera="1"):
    entorno = os.environ.copy()
    entorno.update(
        ENTORNO="desarrollo",
        URL_BASE_DATOS="postgresql+asyncpg://esart_aplicacion:solo-fixture@127.0.0.1/esart_db",
        ESART_MIGRACIONES_URL=lab.url("esart_migrador", BASE),
        ESART_VALIDAR_P0018_COPIA=bandera,
        PYTHONIOENCODING="utf-8",
    )
    return ejecutar(
        [sys.executable, "-m", "alembic", accion, revision],
        entorno=entorno,
        permitir_fallo=True,
    )


