-- Equivale a la revision Alembic p0011_cursos_importacion (esta base no tiene alembic_version).
-- Crea esart.instructores y esart.cursos si faltan, agrega foto a instructores,
-- convierte hoja_vida_artillero en historial (grado, curso_id, unidad_id) y concede a
-- esart_aplicacion solo las columnas que usa la importacion masiva.
-- Generado desde la migracion; si la cambia, vuelva a generarlo.
BEGIN;

CREATE TABLE IF NOT EXISTS esart.instructores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usuario_id BIGINT NOT NULL,
  fecha_ingreso_escuela DATE NOT NULL,
  activo BOOLEAN DEFAULT true NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
  CONSTRAINT instructores_pkey PRIMARY KEY (id),
  CONSTRAINT instructores_usuario_id_key UNIQUE (usuario_id),
  CONSTRAINT fk_instructores_usuario_id FOREIGN KEY (usuario_id) REFERENCES esart_ref.usuarios (id)
);

ALTER TABLE esart.instructores ADD COLUMN IF NOT EXISTS foto BYTEA;

ALTER TABLE esart.instructores ADD COLUMN IF NOT EXISTS foto_tipo VARCHAR(30);

ALTER TABLE esart.instructores DROP CONSTRAINT IF EXISTS ck_instructores_foto;

ALTER TABLE esart.instructores ADD CONSTRAINT ck_instructores_foto CHECK (
  (foto IS NULL AND foto_tipo IS NULL)
  OR (foto IS NOT NULL
      AND foto_tipo IN ('image/jpeg', 'image/png', 'image/webp')
      AND octet_length(foto) BETWEEN 1 AND 2097152)
);

CREATE TABLE IF NOT EXISTS esart.cursos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  tipo_curso_id BIGINT NOT NULL,
  semestre_id BIGINT,
  comandante_id BIGINT NOT NULL,
  codigo VARCHAR(30) NOT NULL,
  nombre VARCHAR(200) NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  estado VARCHAR(20) DEFAULT 'EN_CURSO' NOT NULL,
  observaciones TEXT,
  creado_por_id BIGINT NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
  CONSTRAINT cursos_pkey PRIMARY KEY (id),
  CONSTRAINT cursos_codigo_key UNIQUE (codigo),
  CONSTRAINT ck_cursos_fechas CHECK ((fecha_fin IS NULL) OR (fecha_fin >= fecha_inicio)),
  CONSTRAINT fk_cursos_tipo_curso_id FOREIGN KEY (tipo_curso_id) REFERENCES esart.tipos_curso (id),
  CONSTRAINT fk_cursos_comandante_id FOREIGN KEY (comandante_id) REFERENCES esart.instructores (id),
  CONSTRAINT fk_cursos_creado_por_id FOREIGN KEY (creado_por_id) REFERENCES esart_ref.usuarios (id)
);

ALTER TABLE esart.cursos ALTER COLUMN semestre_id DROP NOT NULL;

ALTER TABLE esart.cursos DROP CONSTRAINT IF EXISTS ck_cursos_estado;

UPDATE esart.cursos SET estado = CASE estado
  WHEN 'EN_EJECUCION' THEN 'EN_CURSO'
  WHEN 'FINALIZADO' THEN 'CULMINADO'
  WHEN 'PLANEADO' THEN 'APLAZADO'
  ELSE estado END;

ALTER TABLE esart.cursos ALTER COLUMN estado SET DEFAULT 'EN_CURSO';

ALTER TABLE esart.cursos ADD CONSTRAINT ck_cursos_estado CHECK (estado IN ('EN_CURSO', 'CULMINADO', 'CANCELADO', 'APLAZADO'));

ALTER TABLE esart.hoja_vida_artillero ADD COLUMN IF NOT EXISTS grado VARCHAR(20);

ALTER TABLE esart.hoja_vida_artillero ADD COLUMN IF NOT EXISTS curso_id BIGINT;

ALTER TABLE esart.hoja_vida_artillero ADD COLUMN IF NOT EXISTS unidad_id BIGINT;

ALTER TABLE esart.hoja_vida_artillero
  DROP CONSTRAINT IF EXISTS fk_hoja_vida_artillero_curso_id,
  DROP CONSTRAINT IF EXISTS fk_hoja_vida_artillero_unidad_id,
  DROP CONSTRAINT IF EXISTS hoja_vida_artillero_artillero_id_key,
  ADD CONSTRAINT fk_hoja_vida_artillero_curso_id
    FOREIGN KEY (curso_id) REFERENCES esart.cursos (id),
  ADD CONSTRAINT fk_hoja_vida_artillero_unidad_id
    FOREIGN KEY (unidad_id) REFERENCES esart_ref.unidades_militares (id);

CREATE INDEX IF NOT EXISTS ix_hoja_vida_artillero_artillero_id ON esart.hoja_vida_artillero (artillero_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_hoja_vida_artillero_curso ON esart.hoja_vida_artillero (artillero_id, curso_id) WHERE curso_id IS NOT NULL;

DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'esart_aplicacion') THEN

GRANT USAGE ON SCHEMA esart, esart_ref TO esart_aplicacion;
GRANT SELECT (id, codigo, nombre, activo) ON esart.tipos_curso TO esart_aplicacion;
GRANT SELECT (id, usuario_id, activo) ON esart.instructores TO esart_aplicacion;
GRANT SELECT (id, usuario, documento_identidad) ON esart_ref.usuarios TO esart_aplicacion;
GRANT SELECT (id, codigo, tipo_curso_id, fecha_inicio, fecha_fin)
  ON esart.cursos TO esart_aplicacion;
GRANT INSERT (tipo_curso_id, comandante_id, codigo, nombre, fecha_inicio, fecha_fin,
              estado, observaciones, creado_por_id)
  ON esart.cursos TO esart_aplicacion;
GRANT SELECT (id, documento_identidad, nombres, apellidos, grado)
  ON esart.personal_militar TO esart_aplicacion;
GRANT INSERT (documento_identidad, nombres, apellidos, grado, genero, categoria,
              unidad_actual_id, especialidad_actual, activo)
  ON esart.personal_militar TO esart_aplicacion;
GRANT UPDATE (grado, actualizado_en) ON esart.personal_militar TO esart_aplicacion;
GRANT SELECT (id, artillero_id, curso_id) ON esart.hoja_vida_artillero TO esart_aplicacion;
GRANT INSERT (artillero_id, grado, curso_id, unidad_id)
  ON esart.hoja_vida_artillero TO esart_aplicacion;

      END IF;
    END $$;

COMMIT;
